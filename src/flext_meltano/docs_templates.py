"""FLEXT-Meltano Documentation Templates.

Template-based generation for CI/CD workflows, Makefiles, and Git hooks
using FLEXT architectural patterns.
"""

from __future__ import annotations

from datetime import UTC, datetime

from flext_core import FlextLogger, FlextResult, u

from flext_meltano.constants import FlextMeltanoConstants
from flext_meltano.models import FlextMeltanoModels
from flext_meltano.typings import FlextMeltanoTypes

# Import aliases for concise usage
t = FlextMeltanoTypes
c = FlextMeltanoConstants
m = FlextMeltanoModels
r = FlextResult


class DocsTemplates:
    """Template-based content generation for documentation automation."""

    def __init__(self, logger: FlextLogger | None = None) -> None:
        """Initialize templates with optional logger."""
        self._logger = logger

    def generate_ci_workflow(self, config: dict[str, object]) -> r[str]:
        """Generate GitHub Actions workflow using template pattern.

        Args:
            config: Automation configuration dictionary

        Returns:
            r containing generated workflow YAML

        """
        try:
            # DSL mnemonic pattern: extract automation fields and construct template vars
            automation_raw = u.extract(config, "automation", default={})
            automation = u.guard(automation_raw, dict, default={}, return_value=True)
            template_vars = u.construct(
                {
                    "generated_at": {
                        "value": datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S"),
                    },
                    "audit_day": {
                        "field": "audit_day",
                        "default": "monday",
                        "ops": {"ensure": "str"},
                    },
                    "audit_time": {
                        "field": "audit_time",
                        "default": "09:00",
                        "ops": {"ensure": "str"},
                    },
                    "cron_schedule": {"value": self._get_cron_schedule(config)},
                },
                source=automation,
            )

            workflow_content = self._ci_workflow_template.format(**template_vars)

            if self._logger:
                self._logger.info("CI workflow template generated", vars=template_vars)

            return r.ok(workflow_content)

        except Exception as e:
            error_msg = f"Failed to generate CI workflow: {e}"
            if self._logger:
                self._logger.exception("CI workflow generation failed", error=error_msg)
            return r.fail(error_msg)

    def generate_makefile_targets(self) -> r[str]:
        """Generate Makefile targets using template pattern.

        Returns:
            r containing generated Makefile content

        """
        try:
            makefile_content = self._makefile_targets_template

            if self._logger:
                self._logger.info("Makefile targets template generated")

            return r.ok(makefile_content)

        except Exception as e:
            error_msg = f"Failed to generate Makefile targets: {e}"
            if self._logger:
                self._logger.exception("Makefile generation failed", error=error_msg)
            return r.fail(error_msg)

    def generate_git_hook(self) -> r[str]:
        """Generate Git pre-commit hook using template pattern.

        Returns:
            r containing generated hook script

        """
        try:
            hook_content = self._git_hook_template

            if self._logger:
                self._logger.info("Git hook template generated")

            return r.ok(hook_content)

        except Exception as e:
            error_msg = f"Failed to generate Git hook: {e}"
            if self._logger:
                self._logger.exception("Git hook generation failed", error=error_msg)
            return r.fail(error_msg)

    @staticmethod
    def _get_cron_schedule(config: dict[str, object]) -> str:
        """Convert audit schedule to cron format."""
        automation_raw = u.extract(config, "automation", default={})
        automation_config = u.guard(automation_raw, dict, default={}, return_value=True)
        audit_day = u.normalize(
            str(u.extract(automation_config, "audit_day", default="monday")),
            case="lower",
        )
        audit_time = str(u.extract(automation_config, "audit_time", default="09:00"))

        hour, minute = map(int, audit_time.split(":"))

        # Day mapping for cron (0=Sunday, 1=Monday, etc.)
        day_map = {
            "sunday": 0,
            "monday": 1,
            "tuesday": 2,
            "wednesday": 3,
            "thursday": 4,
            "friday": 5,
            "saturday": 6,
        }

        day_num = u.get(day_map, audit_day, default=1)  # Default to Monday

        return f"{minute} {hour} * * {day_num}"

    _ci_workflow_template = """# Documentation Quality CI/CD Pipeline
# Generated by FLEXT-Meltano Documentation Maintenance Framework
# Generated: {generated_at}

name: Documentation Quality

on:
  push:
    branches: [ main, develop ]
    paths:
      - 'docs/**'
      - '**.md'
      - 'scripts/docs_maintenance.py'
  pull_request:
    branches: [ main, develop ]
    paths:
      - 'docs/**'
      - '**.md'
      - 'scripts/docs_maintenance.py'
  schedule:
    # Run weekly audit on {audit_day} at {audit_time} UTC
    - cron: '{cron_schedule}'

jobs:
  docs-quality-check:
    runs-on: ubuntu-latest

    steps:
    - name: Checkout code
      uses: actions/checkout@v4

    - name: Set up Python
      uses: actions/setup-python@v4
      with:
        python-version: '3.13'

    - name: Install dependencies
      run: |
        python -m pip install --upgrade pip
        pip install PyYAML requests

    - name: Run documentation quality audit
      run: python scripts/docs_maintenance.py --comprehensive

    - name: Check quality thresholds
      run: python scripts/docs_automation.py --ci-check

    - name: Upload quality reports
      uses: actions/upload-artifact@v4
      if: always()
      with:
        name: docs-quality-reports
        path: docs/reports/

    - name: Comment PR with quality report
      if: github.event_name == 'pull_request'
      uses: actions/github-script@v7
      with:
        script: |
          const fs = require('fs');
          const path = require('path');

          // Read the quality summary
          const summaryPath = path.join(process.cwd(), 'docs/reports/docs_quality_summary.json');
          if (fs.existsSync(summaryPath)) {{
            const summary = JSON.parse(fs.readFileSync(summaryPath, 'utf8'));

            const qualityScore = summary.quality_score;
            const totalIssues = summary.issues.total;

            const body = `
            ## 📊 Documentation Quality Report

            **Quality Score:** ${{qualityScore}}/100
            **Total Issues:** ${{totalIssues}}

            ### Details
            - Files: ${{summary.metrics.total_files}}
            - Words: ${{summary.metrics.total_words.toLocaleString()}}
            - Links: ${{summary.metrics.total_links}}

            [View detailed report](https://github.com/${{github.repository}}/actions/runs/${{github.run_id}})
            `;

            github.rest.issues.createComment({{
              issue_number: context.issue.number,
              owner: context.repo.owner,
              repo: context.repo.repo,
              body: body
            }});
          }}
"""

